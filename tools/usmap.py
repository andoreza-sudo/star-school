def albers(lon, lat, lon0=-96.0, lat0=37.5, p1=29.5, p2=45.5):
    r = math.radians
    n = (math.sin(r(p1)) + math.sin(r(p2))) / 2
    C = math.cos(r(p1)) ** 2 + 2 * n * math.sin(r(p1))
    rho = lambda la: math.sqrt(C - 2 * n * math.sin(r(la))) / n
    th = n * r(lon - lon0)
    return rho(lat) * math.sin(th), rho(lat0) - rho(lat) * math.cos(th)

W, H = 300, 190
def fit(pts_all, box, project):
    xs = [project(*p) for p in pts_all]
    x0, x1 = min(p[0] for p in xs), max(p[0] for p in xs)
    y0, y1 = min(p[1] for p in xs), max(p[1] for p in xs)
    bx, by, bw, bh = box
    k = min(bw / (x1 - x0), bh / (y1 - y0))
    return lambda lon, lat: (lambda p: (round(bx + (p[0] - x0) * k), round(by + (y1 - p[1]) * k)))(project(lon, lat))

def path(rings, f):
    out = ''
    for ring in rings:
        pts = []
        for p in ring:
            q = f(*p)
            if not pts or pts[-1] != q: pts.append(q)
        if len(pts) > 1 and pts[0] == pts[-1]: pts.pop()
        s, prev, mode = '', None, ''
        for i, (x, y) in enumerate(pts):
            if i == 0: s, mode = 'M%d %d' % (x, y), 'M'
            elif x == prev[0]: s, mode = s + 'V%d' % y, 'V'
            elif y == prev[1]: s, mode = s + 'H%d' % x, 'H'
            elif mode in 'ML': s, mode = s + ' %d %d' % (x, y), 'L'
            else: s, mode = s + 'L%d %d' % (x, y), 'L'
            prev = (x, y)
        out += s + 'Z'
    return out

def build():
    lower = fit([p for k, v in S.items() for p in v], (62, 2, W - 64, H - 4), albers)
    ak = fit(AK, (2, 128, 70, 58), lambda lo, la: albers(lo, la, -154, 50, 55, 65))
    hi = fit([p for r in HI for p in r], (74, 156, 40, 28), lambda lo, la: albers(lo, la, -157, 20, 8, 18))
    paths = {}
    for k, v in S.items():
        if len(k) == 3: continue
        rings = [v] + ([S[k + '2']] if k + '2' in S else [])
        paths[k] = path(rings, lower)
    paths['AK'] = path([AK], ak)
    paths['HI'] = path(HI, hi)
    return paths

def check():
    soc = open(os.path.join(os.path.dirname(__file__), '..', 'src', 'data', 'd-disc2-soc.js')).read()
    adj = re.search(r'const DISC_ADJ = `([^`]*)`', soc).group(1)
    want = set()
    for r in adj.strip().split('\n'):
        a, bs = r.split(':')
        for b in bs.split(): want.add(tuple(sorted((a, b))))
    edges = {}
    for k, v in S.items():
        st = k[:2]
        for i in range(len(v)):
            e = tuple(sorted((v[i], v[(i + 1) % len(v)])))
            edges.setdefault(e, set()).add(st)
    got = set()
    for e, sts in edges.items():
        if len(sts) > 1:
            for a in sts:
                for b in sts:
                    if a < b: got.add((a, b))
    print('missing (in DISC_ADJ, not on the map):', sorted(want - got))
    print('extra (on the map, not in DISC_ADJ):', sorted(got - want))
    return want == got

